  assert.equal(rows.length, 1, `${word}: unique permanent test output`);
  const {e, ...expected} = rows[0];
  assert.deepEqual(JSON.parse(JSON.stringify(bank[word])), expected, `${word}: test source/output parity`);
  assert.equal(bank[word].b, word, `${word}: answer uses corrected spelling`);
  assert.ok(json(`tools/test-uretim/girdi/${batch}.json`).some(row => row.e === word));
  assert.ok(!records.some(row => row.e === old));
