'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'../..');
const c={window:{YDS:{},YDS_KELIME_ALIASES:{'old-alpha':'alpha'}}};vm.createContext(c);
vm.runInContext(fs.readFileSync(path.join(root,'assets/js/esitleme-veri.js'),'utf8'),c);
const M=c.window.YDS.EsitlemeMotoru,key='yds-favoriler',plain=v=>JSON.parse(JSON.stringify(v));
assert.equal(M.TIPLER[key],'nesne');
const base=M.zarfaCevir({'yds-leitner':{alpha:{k:5,g:20000,c:20000}},'yds-gunluk-yeni':0,[key]:{'old-alpha':1000}});
assert.deepEqual(plain(M.paket(base)[key]),{alpha:1000},'old vocabulary aliases converge on the favorite word');
const a=M.kayitlariYaz(base,key,{beta:2000},()=> '100:A');
const b=M.kayitlariYaz(base,key,{gamma:3000},()=> '101:B');
const merged=M.birlestir(a,b);
assert.deepEqual(Object.keys(M.paket(merged)[key]).sort(),['alpha','beta','gamma'],'different devices retain each other’s additions');
assert.equal(M.kararliJson(merged),M.kararliJson(M.birlestir(b,a)));
const removed=M.kayitlariSil(merged,key,['alpha'],()=> '200:A');
assert.deepEqual(plain(M.paket(M.birlestir(removed,base))[key]),{beta:2000,gamma:3000},'an old offline snapshot cannot resurrect a removed favorite');
const addedAgain=M.kayitlariYaz(removed,key,{alpha:4000},()=> '201:B');
assert.equal(M.paket(M.birlestir(removed,addedAgain))[key].alpha,4000,'explicit re-add is retained');
const field=removed.alanlar[key];
assert.deepEqual(plain(M.bulutAlaniniCoz(key,JSON.parse(M.bulutAlanJson(key,field)))),plain(field),'cloud serialization retains records and deletion markers');
const progressBefore=plain(M.paket(base));delete progressBefore[key];
const progressAfter=plain(M.paket(addedAgain));delete progressAfter[key];
assert.deepEqual(progressAfter,progressBefore,'favorites never change learning fields');
vm.runInContext(fs.readFileSync(path.join(root,'data/kelime-dizin.js'),'utf8'),c);
const catalog=c.window.KELIME_DIZIN;
const full=Object.fromEntries(catalog.map(d=>[d.e,1794344400000]));
const fullEnvelope=M.kayitlariYaz(M.zarfaCevir({}),key,full,()=> '1794344400000:capacitytest');
assert.ok(Buffer.byteLength(M.bulutAlanJson(key,fullEnvelope.alanlar[key]),'utf8')<921600,'the entire vocabulary catalog fits the cloud field limit');
console.log('Favoriler: alias, iki cihaz birleşimi, silme/yeniden ekleme, bulut kodlaması ve kutu yalıtımı geçti.');
